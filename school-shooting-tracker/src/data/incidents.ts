// loaded from the K-12 SSDB CSV and matching the Incident interface below.

export type IncidentCategory =
  | "mass"           // 4+ killed (excluding shooter), per FBI/Mother Jones definition
  | "targeted"       // targeted attack, multiple victims
  | "altercation"    // dispute / fight that escalated
  | "indiscriminate" // active shooter targeting whoever is present
  | "accidental"
  | "suicide"
  | "officer"        // officer-involved on school grounds
  | "other";

export type SchoolLevel = "elementary" | "middle" | "high" | "k-12" | "college" | "other";

export interface Incident {
  id: string;
  date: string; // ISO YYYY-MM-DD
  school: string;
  city: string;
  state: string; // 2-letter
  lat: number;
  lng: number;
  killed: number; // victims killed (excludes shooter unless noted)
  wounded: number;
  category: IncidentCategory;
  level: SchoolLevel;
  shooterAge?: number;
  shooterRelation?: "current_student" | "former_student" | "staff" | "stranger" | "unknown";
  weaponType?: "handgun" | "rifle" | "shotgun" | "multiple" | "unknown";
  notes?: string;
}

